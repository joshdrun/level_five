blah = [1,7,19,22,24,8]

def is_odd(num):
    if num % 2 == 0:
        odd = False
    else:
        odd = True
    return odd




for i in range(len(blah)):
    if is_odd(blah[i]):
        print(blah[i], "is even")        
    else:
        print(blah[i], "is odd")

print("Done checking numbers, easy peasy")